#!/usr/bin/env python3

import os
import sys
import hashlib
import argparse

def calculate_md5(filepath):
    """Calculate MD5 hash for a file."""
    md5_hash = hashlib.md5()
    
    # Follow symlinks to get the actual file
    actual_path = os.path.realpath(filepath) if os.path.islink(filepath) else filepath
    
    try:
        with open(actual_path, "rb") as f:
            # Read in chunks in case of large files
            for chunk in iter(lambda: f.read(4096), b""):
                md5_hash.update(chunk)
        return md5_hash.hexdigest()
    except Exception as e:
        sys.stderr.write(f"Error calculating MD5 for {filepath}: {str(e)}\n")
        raise

def raise_walk_error(error):
    raise error

def is_raw_file(filepath):
    """Check if file is a raw FASTQ or raw multiqc file (zip or html)."""
    if "/Raw_Sequence_Data/" in filepath:
        # Match raw fastq files
        if filepath.endswith("raw.fastq.gz"):
            return True
        # Match raw multiqc reports (zip or html)
        elif "raw_multiqc" in filepath and (filepath.endswith(".zip") or filepath.endswith(".html")):
            return True
    return False

def should_include(filepath, allowed_dirs):
    """Check if file should be included in MD5 calculation."""
    
    # Skip any files not in the list of workflow output parent directories
    if not any(allowed_dir in filepath for allowed_dir in allowed_dirs):
        return False
    
    # Skip versions.txt files from all directories
    if os.path.basename(filepath) == "versions.txt":
        return False

    # Skip any individual log and count files generated by cutadapt
    if not args.primers_already_trimmed and (filepath.endswith("-cutadapt.log") or filepath.endswith("-trimmed-counts.tsv")):
        return False
    
    # Skip any files with 'fastqc' in the path or filename 
    if 'fastqc' in filepath:
        return False

    # Skip all .png files in alpha diversity and taxonomy plot outputs
    if ("/alpha_diversity/" in filepath or "/taxonomy_plots/" in filepath) and filepath.endswith(".png"):
        return False

    # Skip all .png files in beta diversity except for vsd_validation_plot
    if "/beta_diversity/" in filepath and filepath.endswith(".png") and "vsd_validation_plot" not in filepath:
        return False

    # Skip rarefaction_depth files under alpha/beta diversity
    if ("/alpha_diversity/" in filepath or "/beta_diversity/" in filepath) and "rarefaction_depth" in filepath:
        return False

    # Skip all volcano plots (png) in differential abundance analysis
    if "/differential_abundance/" in filepath and filepath.endswith(".png") and "volcano" in filepath:
        return False
    
    # Skip ISA.zip and GLfile.csv files
    if filepath.endswith("ISA.zip") or filepath.endswith("GLfile.csv"):
        return False

    # Skip files in GeneLab/ except for software_versions, README, processing_info.zip
    if "/GeneLab/" in filepath and not (filepath.endswith("software_versions" + args.assay_suffix + ".txt") or filepath.endswith("README" + args.assay_suffix + ".txt") or filepath.endswith("processing_info" + args.assay_suffix + ".zip")):
        return False
    
    return True

def main():
    parser = argparse.ArgumentParser(description='Generate MD5 sum files for GeneLab data.')
    parser.add_argument('--outdir', required=True, help='Output directory containing files to process')
    parser.add_argument('--readme', help='Generated README to hash before publication')
    parser.add_argument('--processing_info', help='Generated processing archive to hash before publication')
    parser.add_argument('--assay_suffix', default='', help='Suffix for assay type (e.g., _GLAmpSeq or <target_region>_GLAmpSeq, default: empty)')
    parser.add_argument('--output_prefix', default='', help='Prefix for output MD5 sum files (default: empty)')
    parser.add_argument('--generate_raw_md5sums', action='store_true', help='Generate raw MD5sums')
    parser.add_argument('--primers_already_trimmed', action='store_true', help='Indicates if input raw reads have already been primer-trimmed, which means no Trimmed_Sequence_Data/ directory will be generated')
    
    global args
    args = parser.parse_args()
    
    # Make sure outdir is absolute path
    outdir = os.path.abspath(args.outdir)
    
    # Create output files and initialize them without headers
    if args.generate_raw_md5sums:
        raw_md5_file = f"{args.output_prefix}raw_md5sum{args.assay_suffix}.tsv"
        with open(raw_md5_file, 'w') as f:
            f.write("File Path\tFile Name\tmd5\n")
    
    processed_md5_file = f"{args.output_prefix}processed_md5sum{args.assay_suffix}.tsv"
    with open(processed_md5_file, 'w') as f:
        f.write("File Path\tFile Name\tmd5\n")
    
    
    # Track processed files for reporting
    raw_count = 0
    processed_count = 0

    if args.primers_already_trimmed:
        allowed_dirs = [
            "/Metadata/", 
            "/GeneLab/", 
            "/Raw_Sequence_Data/", 
            "/Filtered_Sequence_Data/",
            "/Final_Outputs/"]
    else:
        allowed_dirs = [
            "/Metadata/", 
            "/GeneLab/", 
            "/Raw_Sequence_Data/", 
            "/Trimmed_Sequence_Data/", 
            "/Filtered_Sequence_Data/", 
            "/Final_Outputs/"]
    
    staged_files = {
        f"GeneLab/{os.path.basename(path)}": path
        for path in (args.readme, args.processing_info) if path
    }
    published_dirs = {directory.strip("/") for directory in allowed_dirs}

    # Walk only the top-level publication directories.
    print(f"Scanning directory: {outdir}")
    ancestors = {}
    for root, directories, files in os.walk(outdir, followlinks=True, onerror=raise_walk_error):
        if root == outdir:
            directories[:] = sorted(published_dirs.intersection(directories))
        else:
            directories.sort()
        resolved_root = os.path.realpath(root)
        parent_roots = ancestors.get(os.path.dirname(root), ())
        if resolved_root in parent_roots:
            raise OSError(f"Directory symlink cycle: {root}")
        ancestors[root] = parent_roots + (resolved_root,)
        for filename in sorted(files):
            filepath = os.path.join(root, filename)
            trimmed_path = os.path.relpath(filepath, outdir).replace(os.sep, "/")
            logical_path = "/" + trimmed_path
            
            # The staged files take precedence over copies from earlier runs.
            if trimmed_path in staged_files or not should_include(logical_path, allowed_dirs):
                continue
            
            # Get just the filename (basename)
            basename = os.path.basename(filepath)
            
            # Generate and save md5sum of raw files only if enabled
            if is_raw_file(logical_path):
                if not args.generate_raw_md5sums:
                    continue

                md5sum = calculate_md5(filepath)
                with open(raw_md5_file, 'a') as f:
                    f.write(f"{trimmed_path}\t{basename}\t{md5sum}\n")
                raw_count += 1
            else:
                #Generate and save md5sum of processed files always
                md5sum = calculate_md5(filepath)
                with open(processed_md5_file, 'a') as f:
                    f.write(f"{trimmed_path}\t{basename}\t{md5sum}\n")
                processed_count += 1

    with open(processed_md5_file, 'a') as f:
        for published_path, filepath in staged_files.items():
            md5sum = calculate_md5(filepath)
            f.write(f"{published_path}\t{os.path.basename(filepath)}\t{md5sum}\n")
            processed_count += 1
    
    if args.generate_raw_md5sums:
        print(f"Added {raw_count} files to {raw_md5_file}")
    print(f"Added {processed_count} files to {processed_md5_file}")

    def dedup_file(filename):
        seen = set()
        lines = []
        with open(filename, 'r') as f:
            for line in f:
                key = line.split('\t', 1)[0]  # dedup by basename
                if key not in seen:
                    seen.add(key)
                    lines.append(line)
        with open(filename, 'w') as f:
            f.writelines(lines)

    if args.generate_raw_md5sums:
        dedup_file(raw_md5_file)
    dedup_file(processed_md5_file)

if __name__ == "__main__":
    main()
